// Builds every token output from tokens/*.json (W3C DTCG format).
// Outputs: dist/tokens.css, dist/tailwind.css, dist/tokens.js, dist/tokens.d.ts, dist/tokens.json
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'tokens', f), 'utf8'));
const PREFIX = 'cf';

const base = { ...read('primitives.json'), ...read('typography.json'), ...read('components.json') };
const light = read('semantic.light.json');
const dark = read('semantic.dark.json');

// ---------- flatten ----------
function flatten(tree, path = [], type, out = new Map()) {
  for (const [k, v] of Object.entries(tree)) {
    if (k.startsWith('$') || v === null || typeof v !== 'object') continue;
    const t = v.$type ?? type;
    if ('$value' in v) out.set([...path, k].join('.'), { path: [...path, k], type: t, value: v.$value, description: v.$description });
    else flatten(v, [...path, k], t, out);
  }
  return out;
}
const baseTokens = flatten(base);
const lightTokens = flatten(light);
const darkTokens = flatten(dark);

// light and dark must define exactly the same semantic tokens
const lk = [...lightTokens.keys()].sort().join('|'), dk = [...darkTokens.keys()].sort().join('|');
if (lk !== dk) {
  const a = new Set(lightTokens.keys()), b = new Set(darkTokens.keys());
  throw new Error('Light/dark parity broken: ' + [...a].filter((x) => !b.has(x)).concat([...b].filter((x) => !a.has(x))).join(', '));
}

// ---------- resolve ----------
const REF = /^\{([^}]+)\}$/;
function resolve(value, scope, seen = []) {
  if (typeof value === 'string') {
    const m = value.match(REF);
    if (!m) return value;
    const t = scope.get(m[1]);
    if (!t) throw new Error(`Unresolved reference ${value}`);
    if (seen.includes(m[1])) throw new Error(`Circular reference ${seen.join(' > ')}`);
    return resolve(t.value, scope, [...seen, m[1]]);
  }
  if (Array.isArray(value)) return value.map((v) => resolve(v, scope, seen));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, scope, seen)]));
  return value;
}
const scopeLight = new Map([...baseTokens, ...lightTokens]);
const scopeDark = new Map([...baseTokens, ...darkTokens]);

// ---------- css formatting ----------
const varName = (path) => `--${PREFIX}-${path.join('-')}`;
const fontFamily = (arr) => arr.map((f) => (/[\s]/.test(f) && !f.startsWith('ui-') ? `'${f}'` : f)).join(', ');
function cssValue(token, raw) {
  if (token.type === 'fontFamily') return fontFamily(raw);
  if (token.type === 'cubicBezier') return `cubic-bezier(${raw.join(', ')})`;
  return String(raw);
}
// Semantic tokens keep references as var() so the cascade stays readable in devtools.
function cssRefOrValue(token, scope) {
  const m = typeof token.value === 'string' && token.value.match(REF);
  if (m && scope.has(m[1])) return `var(${varName(scope.get(m[1]).path)})`;
  return cssValue(token, resolve(token.value, scope));
}
function declarations(tokens, scope, indent = '  ') {
  const lines = [];
  for (const t of tokens.values()) {
    if (t.path[0] === 'spring') continue; // JS only
    if (t.type === 'typography') {
      const v = resolve(t.value, scope);
      const n = varName(t.path);
      lines.push(`${indent}${n}-size: ${v.fontSize};`, `${indent}${n}-line-height: ${v.lineHeight};`, `${indent}${n}-tracking: ${v.letterSpacing};`, `${indent}${n}-weight: ${v.fontWeight};`);
      if (v.fontFamily) lines.push(`${indent}${n}-family: ${fontFamily(v.fontFamily)};`);
      continue;
    }
    lines.push(`${indent}${varName(t.path)}: ${cssRefOrValue(t, scope)};`);
  }
  return lines.join('\n');
}

const banner = '/* Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit by hand. */\n';
const tokensCss = `${banner}
:root {
  color-scheme: light;
${declarations(baseTokens, scopeLight)}
${declarations(lightTokens, scopeLight)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${declarations(darkTokens, scopeDark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${declarations(darkTokens, scopeDark)}
}

:root[data-theme='light'] {
  color-scheme: light;
}
`;

