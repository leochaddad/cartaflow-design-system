// ---------- js / json ----------
function nest(tokens, scope) {
  const out = {};
  for (const t of tokens.values()) {
    let o = out;
    t.path.slice(0, -1).forEach((p) => (o = o[p] ??= {}));
    const raw = resolve(t.value, scope);
    o[t.path.at(-1)] = t.type === 'cubicBezier' ? `cubic-bezier(${raw.join(', ')})` : raw;
  }
  return out;
}
const jsBase = nest(baseTokens, scopeLight);
const jsLight = nest(lightTokens, scopeLight);
const jsDark = nest(darkTokens, scopeDark);
const js = `${banner}
export const tokens = ${JSON.stringify(jsBase, null, 2)};

export const themes = ${JSON.stringify({ light: jsLight, dark: jsDark }, null, 2)};

/** CSS custom property for a token path, e.g. cssVar('color.surface.page') -> 'var(--cf-color-surface-page)' */
export const cssVar = (path) => \`var(--${PREFIX}-\${path.split('.').join('-')})\`;
`;
const dts = `${banner}
export declare const tokens: ${JSON.stringify(jsBase)};
export declare const themes: ${JSON.stringify({ light: jsLight, dark: jsDark })};
export declare const cssVar: (path: string) => string;
`;
const flat = {};
