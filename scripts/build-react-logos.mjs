// Turns the master logo SVGs into react/logo-data.ts. Colors become CSS variables (color geometry)
// or currentColor (mono geometry), so 6 schemes cost 2 geometries per lockup.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svg = (name) => readFileSync(join(root, 'logos/svg', `cartaflow-${name}.svg`), 'utf8');
const parse = (s) => ({
  viewBox: s.match(/viewBox="([^"]+)"/)[1],
  body: s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/, '').trim(),
});
const COLOR = { '#CC3421': 'var(--cf-logo-stamp,#CC3421)', '#E6998E': 'var(--cf-logo-frame,#E6998E)', '#FFFEFB': 'var(--cf-logo-inner,#FFFEFB)', '#14213D': 'var(--cf-logo-word,#14213D)' };
const toColor = (b) => b.replace(/fill="(#[0-9A-Fa-f]{6})"/g, (m, c) => (COLOR[c.toUpperCase()] ? `fill="${COLOR[c.toUpperCase()]}"` : m));
const toMono = (b) => b.replace(/fill="#000000"/g, 'fill="currentColor"');

const out = ['// Generated by scripts/build-react-logos.mjs from logos/svg. Do not edit by hand.'];
for (const [key, file] of [['horizontal', 'horizontal'], ['vertical', 'vertical'], ['mark', 'mark'], ['markSimplified', 'mark-simplified'], ['wordmark', 'wordmark']]) {
  const c = parse(svg(`${file}-primary`)), m = parse(svg(`${file}-mono-black`));
  out.push(`export const ${key} = { viewBox: ${JSON.stringify(c.viewBox)}, color: ${JSON.stringify(toColor(c.body))}, mono: ${JSON.stringify(toMono(m.body))} } as const;`);
}
writeFileSync(join(root, 'react/logo-data.ts'), out.join('\n') + '\n');
console.log('react/logo-data.ts written');
